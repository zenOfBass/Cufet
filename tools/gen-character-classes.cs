// Generates src/Interpreter/CharacterClassData.cs — the character classes BOTH backends read.
//
// Run it with:  dotnet run tools/gen-character-classes.cs
//
// ★ Why a generated table, for the reason the case table has one (see tools/gen-case-table.cs):
// asking .NET at run time would tie `is alphabetic` to whichever .NET is installed, and the
// compiled runtime has no .NET to ask. One table read by both backends cannot drift apart, and
// pins the answer to a stated Unicode version.
//
// The three classes, each answered for one code point:
//   alphabetic — Rune.IsLetter: any letter, uncased scripts included (中 and ب are letters).
//   numeric    — Rune.IsDigit: decimal DIGITS only (category Nd), so ½ and Ⅻ are not numeric.
//   whitespace — Rune.IsWhiteSpace: the same 25 characters the lexer skips as space.

using System.Text;

const string OutPath = "src/Interpreter/CharacterClassData.cs";

var classes = new (string Name, string What, Func<Rune, bool> Test)[]
{
    ("AlphabeticRanges", "letters (Rune.IsLetter)",           Rune.IsLetter),
    ("NumericRanges",    "decimal digits (Rune.IsDigit)",     Rune.IsDigit),
    ("WhitespaceRanges", "whitespace (Rune.IsWhiteSpace)",    Rune.IsWhiteSpace),
};

// ── Collect each class as sorted, disjoint start/end ranges ─────────────────────────────────────
var built = new List<(string Name, string What, List<(int start, int end)> Ranges, int Count)>();
foreach (var (name, what, test) in classes)
{
    var ranges = new List<(int start, int end)>();
    int count = 0;
    for (int cp = 0; cp <= 0x10FFFF; cp++)
    {
        if (cp >= 0xD800 && cp <= 0xDFFF) continue;          // lone surrogates are not characters
        if (!test(new Rune(cp))) continue;
        count++;
        if (ranges.Count > 0 && ranges[^1].end == cp - 1) ranges[^1] = (ranges[^1].start, cp);
        else ranges.Add((cp, cp));
    }
    built.Add((name, what, ranges, count));
}

// ── Verify, using the SAME binary search the C runtime and the C# lookup will use ───────────────
foreach (var ((name, _, ranges, _), (_, _, test)) in built.Zip(classes))
    for (int cp = 0; cp <= 0x10FFFF; cp++)
    {
        if (cp >= 0xD800 && cp <= 0xDFFF) continue;
        if (Lookup(ranges, cp) != test(new Rune(cp)))
            throw new Exception($"{name} U+{cp:X4}: table says {Lookup(ranges, cp)}, .NET says {test(new Rune(cp))}");
    }

// ── Emit ────────────────────────────────────────────────────────────────────────────────────────
var outFile = new StringBuilder();
outFile.Append($$"""
// <auto-generated>
//     Generated by tools/gen-character-classes.cs — DO NOT EDIT BY HAND.
//     Regenerate with:  dotnet run tools/gen-character-classes.cs
// </auto-generated>
//
// The character classes BOTH backends read: the interpreter looks up through CharacterClasses, and
// the compiler emits these same numbers into the generated C. One table means the two cannot drift
// apart — see tools/gen-case-table.cs for why that is built in rather than tested for.
//
// Each range is two ints — the first and last code point of a run that is in the class. Ranges
// are sorted and never touch, so a binary search for the last range starting at or before a code
// point finds the only candidate.
//
// Unicode data as of .NET {{Environment.Version}}: {{string.Join(", ", built.Select(b => $"{b.Count} {b.What.Split(' ')[0]} in {b.Ranges.Count} ranges"))}}.

namespace Cufet.Interpreter;

public static class CharacterClassData
{
    /// <summary>The .NET version whose Unicode data this table was generated from.</summary>
    public const string SourceRuntime = "{{Environment.Version}}";


""");

for (int i = 0; i < built.Count; i++)
{
    if (i > 0) outFile.AppendLine();
    EmitRanges(outFile, built[i].Name, built[i].What, built[i].Ranges);
}
outFile.AppendLine("}");

Directory.CreateDirectory(Path.GetDirectoryName(OutPath)!);
File.WriteAllText(OutPath, outFile.ToString().ReplaceLineEndings("\n"));

foreach (var b in built) Console.WriteLine($"{b.Name}: {b.Count} code points in {b.Ranges.Count} ranges");
Console.WriteLine("verified exact for all 1114112 code points");
Console.WriteLine($"wrote {OutPath} ({new FileInfo(OutPath).Length} bytes)");


// ── Helpers ─────────────────────────────────────────────────────────────────────────────────────

static bool Lookup(List<(int start, int end)> ranges, int cp)
{
    int lo = 0, hi = ranges.Count - 1, found = -1;
    while (lo <= hi)
    {
        int mid = (lo + hi) / 2;
        if (ranges[mid].start <= cp) { found = mid; lo = mid + 1; } else hi = mid - 1;
    }
    return found >= 0 && cp <= ranges[found].end;
}

static void EmitRanges(StringBuilder outFile, string name, string what, List<(int start, int end)> ranges)
{
    outFile.AppendLine($"    /// <summary>{what}, as first/last pairs ({ranges.Count} ranges).</summary>");
    outFile.AppendLine($"    public static readonly int[] {name} =");
    outFile.AppendLine("    [");
    for (int i = 0; i < ranges.Count; i += 8)
    {
        var line = new StringBuilder("       ");
        foreach (var (start, end) in ranges.Skip(i).Take(8))
            line.Append($" {start,7}, {end,7},");
        outFile.AppendLine(line.ToString());
    }
    outFile.AppendLine("    ];");
}
